// Generate Rust range tables for minimatch's POSIX named classes.
// Each table is produced by testing Node's own /[\p{...}]/u regexes —
// the exact translations minimatch@10 uses in brace-expressions.js.
const fs = require("fs");

const defs = {
  // name: regex source matching minimatch's translation
  ALPHA: "\\p{L}\\p{Nl}",
  ALNUM: "\\p{L}\\p{Nl}\\p{Nd}",
  WORD: "\\p{L}\\p{Nl}\\p{Nd}\\p{Pc}",
  DIGIT: "\\p{Nd}",
  LOWER: "\\p{Ll}",
  UPPER: "\\p{Lu}",
  PUNCT: "\\p{P}",
  CNTRL: "\\p{Cc}",
  BLANK: "\\p{Zs}\\t",
  SPACE: "\\p{Z}\\t\\r\\n\\v\\f",
  PRINT: "\\p{C}",       // minimatch maps [:print:] to \p{C} (positive)
  GRAPH_NEG: "\\p{Z}\\p{C}", // [:graph:] is negated: member iff NOT in this set
};

function table(src) {
  const re = new RegExp(`^[${src}]$`, "u");
  const ranges = [];
  let lo = -1,
    prev = -1;
  for (let cp = 0; cp <= 0x10ffff; cp++) {
    if (re.test(String.fromCodePoint(cp))) {
      if (lo < 0) lo = cp;
      prev = cp;
    } else if (lo >= 0) {
      ranges.push([lo, prev]);
      lo = -1;
    }
  }
  if (lo >= 0) ranges.push([lo, prev]);
  return ranges;
}

let out = `//! GENERATED FILE — do not edit by hand.\n`;
out += `//!\n`;
out += `//! Unicode range tables for minimatch's POSIX named character classes\n`;
out += `//! (\`[[:name:]]\`). Generated by testing Node's own\n`;
out += `//! \`/^[\\p{...}]$/u\` regexes for every code point 0..=0x10FFFF\n`;
out += `//! (Node ${process.version}, ICU bundled). Each entry is an inclusive\n`;
out += `//! \`(lo, hi)\` code point range, sorted and non-overlapping.\n`;
out += `//!\n`;
out += `//! Regenerate: \`node crates/cheaper-tools/gen-glob-tables.cjs <out-path>\`\n`;
out += `//! (this script lives under crates/cheaper-tools/).\n\n`;

for (const [name, src] of Object.entries(defs)) {
  const t = table(src);
  out += `/// \`[${src}]\` — ${t.length} ranges.\n`;
  out += `pub(crate) const ${name}: &[(u32, u32)] = &[\n`;
  for (const [lo, hi] of t) out += `    (${lo}, ${hi}),\n`;
  out += `];\n\n`;
}

fs.writeFileSync(process.argv[2], out);
for (const [name, src] of Object.entries(defs)) {
  console.log(name, src, "->", table(src).length, "ranges");
}
