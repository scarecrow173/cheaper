#!/usr/bin/env node
// Quarterly root-cause digest generator.
//
// Reads every docs/incidents/INC-*.md report, extracts the root-cause
// statement, clusters incidents by normalized root-cause text, and
// writes reports/root-cause-digest.md.
//
// Extraction convention: the root cause is the first non-empty line
// after the LAST `## ` section heading in each report. Heading names
// vary across reports ("Root cause", "What went wrong",
// "Postmortem notes", "Analysis"), so the script keys on position,
// not on the heading text. Everything after that first line in the
// section is template boilerplate and is ignored.
//
// Re-run each quarter:
//   npm run digest
//   node scripts/digest-incidents.mjs [--max <n>] [--out <path>]
//
// Note: clustering is by normalized text, not semantics. If the same
// underlying cause is worded differently in new reports it lands in a
// separate cluster — review the "Further patterns" appendix and the
// cluster list each quarter and consolidate wording where needed.

import { readdirSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { join, basename, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const incidentsDir = join(root, "docs", "incidents");

function argValue(flag, fallback) {
  const i = process.argv.indexOf(flag);
  return i !== -1 && process.argv[i + 1] ? process.argv[i + 1] : fallback;
}
const maxPatterns = Number.parseInt(argValue("--max", "5"), 10);
const outPath = argValue("--out", join(root, "reports", "root-cause-digest.md"));

const files = readdirSync(incidentsDir)
  .filter((f) => /^INC-.*\.md$/i.test(f))
  .sort();

if (files.length === 0) {
  console.error(`no incident reports found in ${incidentsDir}`);
  process.exit(1);
}

const incidents = files.map((file) => {
  const id = basename(file, ".md");
  const text = readFileSync(join(incidentsDir, file), "utf8");
  const lines = text.split(/\r?\n/);

  // Title: `# <service> — incident report (<date>)`.
  const title = lines.find((l) => l.startsWith("# ")) ?? "";
  const m = title.match(/^#\s+(.*?)\s+[—-]\s+incident report\s+\(([^)]+)\)/);
  const service = m ? m[1] : "unknown";
  const date = m ? m[2] : "unknown";

  // Root cause: first non-empty line after the last `## ` heading.
  let lastHeading = -1;
  lines.forEach((l, i) => {
    if (l.startsWith("## ")) lastHeading = i;
  });
  const cause =
    lastHeading === -1
      ? null
      : (lines.slice(lastHeading + 1).find((l) => l.trim() !== "") ?? "").trim();

  return { id, service, date, cause };
});

const missing = incidents.filter((i) => !i.cause);
if (missing.length > 0) {
  console.error(
    `warning: no root cause found in: ${missing.map((i) => i.id).join(", ")}`,
  );
}

// Cluster by normalized root-cause text.
const norm = (s) => s.replace(/\s+/g, " ").trim().replace(/\.+$/, "");
const clusters = new Map();
for (const inc of incidents) {
  if (!inc.cause) continue;
  const key = norm(inc.cause);
  if (!clusters.has(key)) clusters.set(key, { cause: inc.cause, items: [] });
  clusters.get(key).items.push(inc);
}

const sorted = [...clusters.values()].sort((a, b) => {
  if (b.items.length !== a.items.length) return b.items.length - a.items.length;
  return a.items[0].id.localeCompare(b.items[0].id);
});

// Label: text before the first sentence/clause boundary
// (`.`/`:`/`—`/`;`), else the first ~12 words.
const labelOf = (cause) => {
  const head = cause.split(/[:—;.]/)[0].trim();
  const words = head.split(/\s+/);
  return words.length <= 12 ? head : words.slice(0, 12).join(" ") + "…";
};

const top = sorted.slice(0, maxPatterns);
const rest = sorted.slice(maxPatterns);

const fmtList = (items) =>
  items.map((i) => `\`${i.id}\` (${i.service}, ${i.date})`).join(", ");

const out = [];
out.push("# Root-cause digest");
out.push("");
out.push(
  `Generated by \`npm run digest\` (\`node scripts/digest-incidents.mjs\`)`,
);
out.push(
  `from \`docs/incidents/\` — ${incidents.length} incidents scanned,`,
);
out.push(
  `${sorted.length} distinct root cause(s) found; top ${top.length} shown.`,
);
out.push(`Do not edit by hand — re-run the command to refresh.`);
out.push("");
out.push(`## Recurring patterns`);
out.push("");
top.forEach((c, idx) => {
  const rep = c.items[0];
  out.push(`### ${idx + 1}. ${labelOf(c.cause)} (${c.items.length} incidents)`);
  out.push("");
  out.push(`**Representative:** \`${rep.id}\` (${rep.service}, ${rep.date})`);
  out.push("");
  out.push(`> ${c.cause}`);
  out.push("");
  out.push(`**Occurrences:** ${fmtList(c.items)}`);
  out.push("");
});
if (rest.length > 0) {
  out.push(`## Further patterns (outside top ${maxPatterns} — review and consolidate)`);
  out.push("");
  for (const c of rest) {
    out.push(`- **${labelOf(c.cause)}** (${c.items.length}): ${fmtList(c.items)}`);
    out.push(`  - ${c.cause}`);
  }
  out.push("");
}
out.push(`## Re-running this digest`);
out.push("");
out.push(
  `Quarterly: run \`npm run digest\` (or \`node scripts/digest-incidents.mjs\`)`,
);
out.push(
  `to regenerate this file from whatever \`docs/incidents/\` contains.`,
);
out.push(`Options: \`--max <n>\` changes the pattern cap, \`--out <path>\``);
out.push(`changes the output file.`);
out.push("");
out.push(
  `The script clusters by normalized root-cause text taken from the last`,
);
out.push(
  `\`## \` section of each report. If a known cause is worded differently`,
);
out.push(
  `in newer reports it appears as a separate pattern — consolidate the`,
);
out.push(`report wording, then re-run.`);
out.push("");

mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, out.join("\n"), "utf8");
console.log(
  `wrote ${outPath} — ${incidents.length} incidents, ${sorted.length} pattern(s), top ${top.length} listed`,
);
