#!/usr/bin/env node
// Generates reports/api-inventory.md from the API specs under docs/.
//
// Usage:
//   node scripts/generate-api-inventory.mjs          # write the report
//   node scripts/generate-api-inventory.mjs --check  # fail if the report is stale
//   npm run inventory                                # same, via package.json
//
// Each docs file is expected to follow the repo convention:
//   - filename: <domain>-<topic>.md   (domain = service area)
//   - endpoints declared as `### <METHOD> /<path>` headings
//   - a one-line summary on the first non-empty line after each heading

import { readdirSync, readFileSync, mkdirSync, writeFileSync } from "node:fs";
import { join, dirname, basename, relative } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const DOCS_DIR = join(ROOT, "docs");
const REPORT = join(ROOT, "reports", "api-inventory.md");

// Canonical domain order; any other domain found in docs/ is appended
// alphabetically after these.
const DOMAIN_ORDER = ["billing", "auth", "notify", "ledger", "catalog", "shipping"];

const ENDPOINT_RE = /^###\s+([A-Z]+)\s+(\/\S+)\s*$/;
const TITLE_RE = /^#\s+([a-z0-9]+)/;

function domainOf(filename, content) {
  const stem = basename(filename, ".md");
  const dash = stem.indexOf("-");
  if (dash > 0) return stem.slice(0, dash);
  const title = content.match(TITLE_RE);
  if (title) return title[1];
  return "other";
}

function parseFile(filename) {
  const content = readFileSync(join(DOCS_DIR, filename), "utf8");
  const domain = domainOf(filename, content);
  const endpoints = [];
  const lines = content.split(/\r?\n/);
  for (let i = 0; i < lines.length; i++) {
    const m = lines[i].match(ENDPOINT_RE);
    if (!m) continue;
    const [, method, path] = m;
    let summary = "";
    for (let j = i + 1; j < lines.length; j++) {
      const line = lines[j].trim();
      if (!line) continue;
      if (line.startsWith("|") || line.startsWith("#")) break;
      summary = line;
      break;
    }
    endpoints.push({ method, path, summary, source: `docs/${filename}` });
  }
  return { domain, endpoints };
}

function collect() {
  const files = readdirSync(DOCS_DIR)
    .filter((f) => f.endsWith(".md"))
    .sort();
  const byDomain = new Map();
  for (const file of files) {
    const { domain, endpoints } = parseFile(file);
    if (!byDomain.has(domain)) byDomain.set(domain, []);
    byDomain.get(domain).push(...endpoints);
  }
  return { files, byDomain };
}

function sortDomains(domains) {
  const known = DOMAIN_ORDER.filter((d) => domains.includes(d));
  const extra = domains.filter((d) => !DOMAIN_ORDER.includes(d)).sort();
  return [...known, ...extra];
}

function render(files, byDomain) {
  const domains = sortDomains([...byDomain.keys()]);
  const total = [...byDomain.values()].reduce((n, e) => n + e.length, 0);
  const out = [
    "# API Inventory",
    "",
    "<!-- Generated by scripts/generate-api-inventory.mjs — do not edit by hand.",
    "     Regenerate with `npm run inventory` after docs/ changes. -->",
    "",
    `- Source: \`docs/*.md\` (${files.length} files)`,
    `- Service domains: ${domains.length}`,
    `- Endpoints: ${total}`,
    "",
  ];
  for (const domain of domains) {
    const endpoints = byDomain
      .get(domain)
      .slice()
      .sort((a, b) => a.path.localeCompare(b.path) || a.method.localeCompare(b.method));
    out.push(`## ${domain} (${endpoints.length})`, "");
    out.push("| Method | Path | Summary | Source |");
    out.push("|---|---|---|---|");
    for (const e of endpoints) {
      const src = basename(e.source);
      out.push(`| ${e.method} | \`${e.path}\` | ${e.summary} | [${src}](../${e.source}) |`);
    }
    out.push("");
  }
  return out.join("\n");
}

function main() {
  const check = process.argv.includes("--check");
  const { files, byDomain } = collect();
  const content = render(files, byDomain);

  if (check) {
    let current = null;
    try {
      current = readFileSync(REPORT, "utf8");
    } catch {}
    if (current !== content) {
      console.error("reports/api-inventory.md is stale — run `npm run inventory`.");
      process.exit(1);
    }
    console.log("reports/api-inventory.md is up to date.");
    return;
  }

  mkdirSync(dirname(REPORT), { recursive: true });
  writeFileSync(REPORT, content);
  const total = [...byDomain.values()].reduce((n, e) => n + e.length, 0);
  console.log(
    `Wrote ${relative(ROOT, REPORT)}: ${total} endpoints in ${byDomain.size} domains from ${files.length} docs files.`,
  );
}

main();
