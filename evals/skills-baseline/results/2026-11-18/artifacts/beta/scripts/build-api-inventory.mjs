#!/usr/bin/env node
// Regenerate reports/api-inventory.md from docs/*.md.
//
// Each docs file declares its service domain on the H1 line
// (`# <domain> — <topic>`; filename prefix is the fallback) and lists
// endpoints as `### <METHOD> <path>` headings followed by a one-line
// description. This script scans every Markdown file under docs/,
// groups the endpoints by domain, and writes a Markdown table per
// domain to reports/api-inventory.md.
//
// Usage: node scripts/build-api-inventory.mjs  (or: npm run inventory)

import { readdirSync, readFileSync, mkdirSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(fileURLToPath(import.meta.url), "..", "..");
const DOCS_DIR = join(ROOT, "docs");
const OUT_FILE = join(ROOT, "reports", "api-inventory.md");

// Preferred section order; unknown domains are appended alphabetically.
const DOMAIN_ORDER = ["billing", "auth", "notify", "ledger", "catalog", "shipping"];
const METHOD_ORDER = ["GET", "POST", "PUT", "PATCH", "DELETE", "HEAD", "OPTIONS"];

const H1_RE = /^#\s+([A-Za-z0-9_-]+)\s+[—–-]/;
const ENDPOINT_RE = /^###\s+(GET|POST|PUT|PATCH|DELETE|HEAD|OPTIONS)\s+(\S+)\s*$/;

function listMarkdownFiles(dir) {
  const files = [];
  for (const entry of readdirSync(dir, { withFileTypes: true, recursive: true })) {
    if (entry.isFile() && entry.name.toLowerCase().endsWith(".md")) {
      // `recursive` dirents carry parentPath (Node 20.12+); fall back to dir.
      files.push(join(entry.parentPath ?? dir, entry.name));
    }
  }
  return files.sort();
}

function parseFile(path) {
  const lines = readFileSync(path, "utf8").split(/\r?\n/);
  let domain = null;
  const endpoints = [];

  for (let i = 0; i < lines.length; i++) {
    const line = lines[i];
    if (domain === null) {
      const h1 = line.match(H1_RE);
      if (h1) domain = h1[1].toLowerCase();
    }
    const ep = line.match(ENDPOINT_RE);
    if (ep) {
      // Description: first non-blank, non-table line after the heading.
      let description = "";
      for (let j = i + 1; j < lines.length; j++) {
        const next = lines[j].trim();
        if (next === "") continue;
        if (next.startsWith("|") || next.startsWith("#")) break;
        description = next;
        break;
      }
      endpoints.push({ method: ep[1], path: ep[2], description });
    }
  }

  if (domain === null) {
    // Fallback: filename prefix before the first '-'.
    domain = relative(DOCS_DIR, path).replace(/\\/g, "/").split("/").pop().split("-")[0];
  }
  return { domain, endpoints };
}

function escapeCell(text) {
  return text.replace(/\|/g, "\\|").trim();
}

function main() {
  const files = listMarkdownFiles(DOCS_DIR);
  const byDomain = new Map();
  let total = 0;
  const seen = new Map(); // "METHOD path" -> first source file
  const duplicates = [];

  for (const file of files) {
    const rel = relative(ROOT, file).replace(/\\/g, "/");
    const { domain, endpoints } = parseFile(file);
    if (!byDomain.has(domain)) byDomain.set(domain, []);
    for (const ep of endpoints) {
      byDomain.get(domain).push({ ...ep, source: rel });
      total++;
      const key = `${ep.method} ${ep.path}`;
      if (seen.has(key)) duplicates.push(`${key} (${seen.get(key)}, ${rel})`);
      else seen.set(key, rel);
    }
  }

  const domains = [...byDomain.keys()].sort((a, b) => {
    const ia = DOMAIN_ORDER.indexOf(a);
    const ib = DOMAIN_ORDER.indexOf(b);
    if (ia !== -1 || ib !== -1) return (ia === -1 ? Infinity : ia) - (ib === -1 ? Infinity : ib);
    return a.localeCompare(b);
  });

  const out = [
    "# API inventory",
    "",
    "<!-- Generated by scripts/build-api-inventory.mjs — do not edit by hand.",
    "     Regenerate with: npm run inventory -->",
    "",
    `${total} endpoints across ${domains.length} service domains (source: docs/).`,
    "",
  ];

  for (const domain of domains) {
    const eps = byDomain.get(domain).sort((a, b) => {
      const byPath = a.path.localeCompare(b.path);
      if (byPath !== 0) return byPath;
      return METHOD_ORDER.indexOf(a.method) - METHOD_ORDER.indexOf(b.method);
    });
    out.push(`## ${domain} (${eps.length})`, "");
    out.push("| Method | Path | Description | Source |");
    out.push("|---|---|---|---|");
    for (const ep of eps) {
      out.push(`| ${ep.method} | \`${ep.path}\` | ${escapeCell(ep.description)} | ${ep.source} |`);
    }
    out.push("");
  }

  if (duplicates.length > 0) {
    out.push("## Duplicate endpoint declarations", "");
    for (const d of duplicates) out.push(`- ${d}`);
    out.push("");
  }

  mkdirSync(join(ROOT, "reports"), { recursive: true });
  writeFileSync(OUT_FILE, out.join("\n"), "utf8");
  console.log(
    `wrote ${relative(ROOT, OUT_FILE)}: ${total} endpoints, ${domains.length} domains, ${files.length} files scanned` +
      (duplicates.length ? ` (${duplicates.length} duplicate declarations)` : ""),
  );
}

main();
