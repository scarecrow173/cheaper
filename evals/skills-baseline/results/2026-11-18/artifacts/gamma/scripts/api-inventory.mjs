#!/usr/bin/env node
// Regenerates reports/api-inventory.md from the API spec files in docs/.
//
// Endpoint convention: each docs/*.md file declares endpoints as
// `### <METHOD> /<path>` headings; the first non-empty line after the
// heading is taken as the description. Service domain is the filename
// prefix before the first `-` (billing-*.md -> billing).
//
// Usage: node scripts/api-inventory.mjs   (or: npm run inventory)
// Output is deterministic — no timestamps, stable sort — so re-runs on
// unchanged docs produce byte-identical reports.

import { mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { basename, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const docsDir = join(root, 'docs');
const reportsDir = join(root, 'reports');
const outPath = join(reportsDir, 'api-inventory.md');

// Preferred section order; any other domain sorts alphabetically after these.
const DOMAIN_ORDER = ['billing', 'auth', 'notify', 'ledger', 'catalog', 'shipping'];
const METHOD_ORDER = ['GET', 'POST', 'PUT', 'PATCH', 'DELETE', 'HEAD', 'OPTIONS'];
const ENDPOINT_RE = /^###\s+(GET|POST|PUT|PATCH|DELETE|HEAD|OPTIONS)\s+(\/\S+)\s*$/;

function extractEndpoints(file) {
  const domain = basename(file, '.md').split('-')[0];
  const lines = readFileSync(join(docsDir, file), 'utf8').split(/\r?\n/);
  const endpoints = [];
  for (let i = 0; i < lines.length; i++) {
    const m = lines[i].match(ENDPOINT_RE);
    if (!m) continue;
    let description = '';
    for (let j = i + 1; j < lines.length; j++) {
      const line = lines[j].trim();
      if (!line) continue;
      // Skip if the next content is a table row or another heading.
      if (!line.startsWith('|') && !line.startsWith('#')) description = line;
      break;
    }
    endpoints.push({ method: m[1], path: m[2], description, source: file, domain });
  }
  return endpoints;
}

const files = readdirSync(docsDir)
  .filter((f) => f.endsWith('.md'))
  .sort();

const all = files.flatMap(extractEndpoints);

const byDomain = new Map();
for (const ep of all) {
  if (!byDomain.has(ep.domain)) byDomain.set(ep.domain, []);
  byDomain.get(ep.domain).push(ep);
}

const domains = [...byDomain.keys()].sort((a, b) => {
  const ia = DOMAIN_ORDER.indexOf(a);
  const ib = DOMAIN_ORDER.indexOf(b);
  if (ia !== -1 || ib !== -1) return (ia === -1 ? Infinity : ia) - (ib === -1 ? Infinity : ib);
  return a.localeCompare(b);
});

const methodRank = (m) => {
  const i = METHOD_ORDER.indexOf(m);
  return i === -1 ? METHOD_ORDER.length : i;
};
const byPathThenMethod = (a, b) =>
  a.path.localeCompare(b.path) || methodRank(a.method) - methodRank(b.method);

// Same method+path defined in more than one place — surfaces doc drift.
const seen = new Map();
for (const ep of all) {
  const key = `${ep.method} ${ep.path}`;
  if (!seen.has(key)) seen.set(key, []);
  seen.get(key).push(ep);
}
const duplicates = [...seen.entries()].filter(([, eps]) => eps.length > 1);

const esc = (s) => s.replace(/\|/g, '\\|');
const out = [];
out.push('# API Endpoint Inventory');
out.push('');
out.push('Generated by `npm run inventory` (`node scripts/api-inventory.mjs`) from `docs/*.md`.');
out.push('Do not edit by hand — re-run the script after changing docs.');
out.push('');
out.push(
  `${files.length} files scanned · ${all.length} endpoints · ${domains.length} service domains`
);
out.push('');
for (const domain of domains) {
  const eps = byDomain.get(domain).slice().sort(byPathThenMethod);
  out.push(`## ${domain} (${eps.length})`);
  out.push('');
  out.push('| Method | Path | Description | Source |');
  out.push('|---|---|---|---|');
  for (const ep of eps) {
    out.push(
      `| \`${ep.method}\` | \`${ep.path}\` | ${esc(ep.description)} | [${ep.source}](../docs/${ep.source}) |`
    );
  }
  out.push('');
}
if (duplicates.length > 0) {
  out.push('## Duplicate definitions');
  out.push('');
  out.push('The same method + path is documented in more than one file:');
  out.push('');
  for (const [key, eps] of duplicates.sort((a, b) => a[0].localeCompare(b[0]))) {
    out.push(`- \`${key}\` — ${eps.map((e) => e.source).join(', ')}`);
  }
  out.push('');
}

mkdirSync(reportsDir, { recursive: true });
writeFileSync(outPath, out.join('\n'), 'utf8');

console.log(
  `wrote ${basename(reportsDir)}/${basename(outPath)}: ${all.length} endpoints across ${domains.length} domains (${files.length} files)`
);
for (const domain of domains) {
  console.log(`  ${domain}: ${byDomain.get(domain).length}`);
}
if (duplicates.length > 0) {
  console.log(`  duplicates: ${duplicates.length}`);
}
